PROMPT = """你是伊斯兰圣训学专家。请为以下圣训编写完整的"翻译与注解"资料，要求：
1. 阿语原文：使用公认的圣训文本（若我提供的原文有缺，请补充完整并说明）
2. 中文翻译：准确、通顺，符合穆斯林学术规范
3. 注解（نحو 100-150字）：说明圣训背景、传述情况、教法要点或现实启示
4. 出处：标注所属圣训集（我提供）

只输出 JSON，格式：
{{"ar": "完整阿语原文（含标符）", "cn": "中文翻译", "note": "注解", "source_cn": "布哈里圣训实录·第X段（编号如不确定写'参见'）"}}

圣训主题：{topic}
阿语原文（可能不完整）：{ar}
所属：{book_cn}（{book_ar}）"""

def main():
    key = get_key()
    if not key:
        print('没有 API key')
        sys.exit(1)
    out_file = DIR / 'data' / 'hadith.json'
    all_data = []
    if out_file.exists():
        all_data = json.load(open(out_file, encoding='utf-8'))
    done = {d['topic'] for d in all_data}
    for i, (book, book_cn, topic, ar) in enumerate(HADITHS):
        if topic in done:
            print(f'跳过: {topic}')
            continue
        book_cn_full, book_ar = BOOKS[book]
        print(f'[{i+1}/{len(HADITHS)}] {topic}...')
        body = None
        for _ in range(3):
            body = chat(PROMPT.format(topic=topic, ar=ar, book_cn=book_cn_full, book_ar=book_ar), key)
            if body:
                m = re.search(r'\{[\s\S]*\}', body)
                if m:
                    try:
                        d = json.loads(m.group(0))
                        if d.get('ar') and d.get('cn'):
                            body = d
                            break
                    except Exception:
                        pass
            print('  重试...')
            time.sleep(3)
        if isinstance(body, dict) and body.get('ar') and body.get('cn'):
            body['book'] = book
            body['book_cn'] = book_cn_full
            body['topic'] = topic
            body['icon'] = '📜'
            all_data.append(body)
            json.dump(all_data, open(out_file, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
            print(f"  ✓ {body['cn'][:30]}...")
        else:
            print('  ✗ 失败，跳过')
        time.sleep(1.5)
    print(f'完成：{len(all_data)} 则')
    json.dump(all_data, open(out_file, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)

if __name__ == '__main__':
    main()
